    /** @return list<list<string|null>>|null */
    public static function colors(string $artName, int $width, int $height): ?array
    {
        $grid = self::GRIDS[$artName] ?? null;
        if ($grid === null) {
            return null;
        }
        if (count($grid) !== $height) {
            throw new \LogicException(sprintf('Color grid %s needs %d rows, got %d', $artName, $height, count($grid)));
        }
        $palette = [];
        foreach (self::PALETTE as $key => $hex) {
            if (strlen((string) $key) !== 1 || $key === '.' || preg_match('/\A#[a-fA-F0-9]{6}\z/', $hex) !== 1) {
                throw new \LogicException('Colors require a one-character key and a #RRGGBB value');
            }
            $palette[$key] = implode(';', [hexdec(substr($hex, 1, 2)), hexdec(substr($hex, 3, 2)), hexdec(substr($hex, 5, 2))]);
        }
        $colors = [];
        foreach ($grid as $y => $line) {
            if (strlen($line) !== $width) {
                throw new \LogicException(sprintf('Color grid %s row %d needs %d letters, got %d', $artName, $y + 1, $width, strlen($line)));
            }
            foreach (str_split($line) as $x => $key) {
                if ($key !== '.' && !isset($palette[$key])) {
                    throw new \LogicException(sprintf('Unknown color %s in %s, row %d, column %d', $key, $artName, $y + 1, $x + 1));
                }
                $colors[$y][$x] = $key === '.' ? null : $palette[$key];
            }
        }

        return $colors;
    }
